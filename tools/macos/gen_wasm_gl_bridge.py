#!/usr/bin/env python3
"""Generate the OpenGL bridge for the macOS wasm sandbox build.

Reads the glad prototypes in include/platform/native_glad.h, keeps the GL
functions the native platform layer actually calls, and writes:

  include/platform/wasm/guest_gl.h   guest-side wasm import declarations
  platform/wasm_host/host_gl.gen.c   host-side wasm2c import implementations

Rerun after the renderer starts calling a new GL function.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GLAD_HEADER = ROOT / "include/platform/native_glad.h"
GUEST_OUT = ROOT / "include/platform/wasm/guest_gl.h"
HOST_OUT = ROOT / "platform/wasm_host/host_gl.gen.c"
SCAN = [ROOT / "main.c"] + sorted(p for p in (ROOT / "platform").glob("*.c") if p.name != "native_glad.c")

TYPEDEF_RE = re.compile(r"typedef\s+([^;()]+?)\s*\(APIENTRYP\s+PFN(\w+)PROC\)\s*\(([^;]*?)\);", re.S)
DEFINE_RE = re.compile(r"#define\s+(gl[A-Z]\w*)\s+glad_\1\b")

F32_TYPES = {"GLfloat", "GLclampf"}
F64_TYPES = {"GLdouble", "GLclampd"}
SIGNED_PTR_SIZED = {"GLsizeiptr", "GLintptr"}
U64_TYPES = {"GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT"}

# NOTE: These GL entry points take a pointer argument that is a buffer offset
# (with a VBO/IBO bound), not guest memory. Pass the raw value through.
OFFSET_POINTER_ARGS = {("glVertexAttribPointer", 5)}

# NOTE: KHR_debug is not exposed by Apple's OpenGL, and the guest only calls
# these when GLAD_GL_KHR_debug is set, which the sandbox reports as 0.
NOOP_FUNCS = {"glPushDebugGroup", "glPopDebugGroup"}


def wasm_type(ctype):
    ctype = ctype.strip()
    if "*" in ctype:
        return "u32"
    base = ctype.replace("const", "").strip()
    if base in F32_TYPES:
        return "f32"
    if base in F64_TYPES:
        return "f64"
    if base in U64_TYPES:
        return "u64"
    return "u32"


def split_params(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    out = []
    for raw in params.split(","):
        raw = raw.strip()
        m = re.match(r"(.*?)(\w+)$", raw)
        ctype, name = m.group(1).strip(), m.group(2)
        out.append((ctype, name))
    return out


def main():
    header = GLAD_HEADER.read_text()
    protos = {}
    for m in TYPEDEF_RE.finditer(header):
        ret, pfn, params = m.group(1), m.group(2), " ".join(m.group(3).split())
        protos[pfn] = (ret.strip(), split_params(params))

    names = {}
    for m in DEFINE_RE.finditer(header):
        name = m.group(1)
        pfn = name.upper()
        if pfn in protos:
            names[name] = protos[pfn]

    used = set()
    ident_re = re.compile(r"\b(gl[A-Z]\w*)\s*\(")
    for path in SCAN:
        for m in ident_re.finditer(path.read_text(errors="replace")):
            if m.group(1) in names:
                used.add(m.group(1))

    guest = [
        "// Generated by tools/macos/gen_wasm_gl_bridge.py. Do not edit.",
        "// Guest-side GL entry points for the wasm sandbox build: each glad",
        "// function pointer macro is replaced with a direct wasm import.",
        "#ifndef CTR_WASM_GUEST_GL_H",
        "#define CTR_WASM_GUEST_GL_H",
        "",
        "#define CTR_WASM_GL_IMPORT(name) __attribute__((import_module(\"env\"), import_name(#name)))",
        "",
    ]
    host = [
        "// Generated by tools/macos/gen_wasm_gl_bridge.py. Do not edit.",
        "// Host-side GL imports for the wasm sandbox build.",
        "",
        "#include \"host_gl.h\"",
        "",
    ]

    for name in sorted(used):
        ret, params = names[name]
        param_decl = ", ".join(f"{t} {n}" for t, n in params) or "void"
        guest.append(f"#undef {name}")
        guest.append(f"CTR_WASM_GL_IMPORT({name}) {ret} {name}({param_decl});")

        ret_w = None if ret == "void" else wasm_type(ret)
        host_params = ["struct w2c_env *env"] + [f"{wasm_type(t)} a{i}" for i, (t, _) in enumerate(params)]
        host.append(f"{ret_w or 'void'} w2c_env_{name}({', '.join(host_params)})")
        host.append("{")
        host.append("\t(void)env;")

        if name in NOOP_FUNCS:
            for i in range(len(params)):
                host.append(f"\t(void)a{i};")
            if ret_w:
                host.append("\treturn 0;")
            host.append("}")
            host.append("")
            continue

        if name == "glShaderSource":
            host.append("\tHostGL_ShaderSource(env, a0, (GLsizei)a1, a2, a3);")
            host.append("}")
            host.append("")
            continue

        args = []
        for i, (ctype, _) in enumerate(params):
            if "*" in ctype:
                if ctype.count("*") > 1:
                    sys.exit(f"ERROR: {name} has a pointer-to-pointer parameter; add a hand-written shim")
                if (name, i) in OFFSET_POINTER_ARGS:
                    args.append(f"({ctype})(uintptr_t)a{i}")
                else:
                    args.append(f"({ctype})HOST_G2H(env, a{i})")
            elif ctype in SIGNED_PTR_SIZED:
                # NOTE: Pointer-sized signed GL types are 32-bit in the guest; sign-extend them.
                args.append(f"({ctype})(s32)a{i}")
            else:
                args.append(f"({ctype})a{i}")
        call = f"{name}({', '.join(args)})"

        if ret == "void":
            host.append(f"\t{call};")
        elif "*" in ret:
            if name != "glGetString":
                sys.exit(f"ERROR: {name} returns a pointer; add a hand-written shim")
            host.append(f"\treturn HostMem_StringToGuest(env, (const char *){call});")
        else:
            host.append(f"\treturn ({ret_w}){call};")
        host.append("}")
        host.append("")

    guest += ["", "#endif", ""]

    GUEST_OUT.parent.mkdir(parents=True, exist_ok=True)
    HOST_OUT.parent.mkdir(parents=True, exist_ok=True)
    GUEST_OUT.write_text("\n".join(guest))
    HOST_OUT.write_text("\n".join(host))
    print(f"{len(used)} GL functions -> {GUEST_OUT.relative_to(ROOT)}, {HOST_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
